/*********************************************************************************************************************
* 文件名称          MotorPID
* 功能简介          电机速度闭环模块（增量式 PID，左右轮独立控制）
*
*   目标：分别追踪左右轮目标；转弯提高外轮目标；达到单轮上限时协调降低内轮，保持差速比。
*   反馈：每侧各自的编码器计数（单位：每 10ms 的计数）。
*   输出：左右独立计算占空比 0 ~ MOTOR_DUTY_MAX，写进 Motor_Set(left, right)。
*
*   控制周期：建议在 20ms 中断里调 MotorPID_Update()。
*   起步软启动：使能后，目标速度用 1 秒慢慢爬到设定值，不会一下冲出去。
********************************************************************************************************************/

#ifndef __MOTORPID_H
#define __MOTORPID_H

#include "zf_common_headfile.h"
#include "Motor.h"

//==================================== 默认参数 ====================================

#define MOTORPID_DEFAULT_TARGET   (80.0f)    // 默认目标速度（编码器计数/10ms）
#define MOTORPID_DEFAULT_KP       (8.0f)     // 比例
#define MOTORPID_DEFAULT_KI       (0.15f)    // 积分
#define MOTORPID_DEFAULT_KD       (0.0f)     // 微分
#define MOTORPID_RAMP_MS          (1000.0f)  // 起步软启动时长（毫秒）
#define MOTORPID_MAX_DUTY         (MOTOR_DUTY_MAX)   // 输出占空比上限

// 用户已停车手转轮确认 L/R 与物理左右轮一致，允许外轮辅助差速，正常循迹由连续图像大偏差控制介入。
#define MOTORPID_DIFFERENTIAL_ENABLE (1)
#define MOTORPID_DIFF_MAX_RATIO     (0.60f)  // 外轮/内轮最大1.60，正常大弯70/112
#define MOTORPID_DIFF_STEP          (0.06f)  // 每20ms差速比最多增加6个百分点，满幅约200ms
#define MOTORPID_MIN_RUN_TARGET     (70.0f)  // 正常运行目标下限；停车为0，起步仍保留软启动
#define MOTORPID_WHEEL_TARGET_MAX   (240.0f) // 单轮目标上限，不扩大现有调速范围

//==============================================================================================

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     初始化（复位 PID 内部状态，设默认参数）
//-------------------------------------------------------------------------------------------------------------------
void MotorPID_Init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置目标速度
// 参数说明     target      目标速度（编码器计数/10ms，>=0）
//-------------------------------------------------------------------------------------------------------------------
void MotorPID_SetTarget(float target);

// 正数左弯，负数右弯，输入 -1..1；直行传 0。协调左右轮速度目标，不修改舵机。
void MotorPID_SetTurn(float turn);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置 PID 三个参数
//-------------------------------------------------------------------------------------------------------------------
void MotorPID_SetGains(float kp, float ki, float kd);
// 调试模式：分别设置左右轮；调用普通 SetTarget 后恢复循迹目标/差速。
void MotorPID_SetWheelTargets(float left, float right);
void MotorPID_SetWheelGains(float lp, float li, float ld, float rp, float ri, float rd);
int MotorPID_GetOutputLeft(void);
int MotorPID_GetOutputRight(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     使能 / 停止
// 参数说明     enable      1 = 跑；0 = 立刻停（电机刹车，PID 复位）
//-------------------------------------------------------------------------------------------------------------------
void MotorPID_SetEnable(uint8 enable);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     每个控制周期调一次（20ms 中断里）
// 参数说明     enc_l / enc_r      左右编码器最近一个 10ms 周期的计数
// 返回参数     int                左右输出占空比的平均值（0~4000）
// 备注信息     停用状态会直接 Motor_Stop() 并返回 0
//-------------------------------------------------------------------------------------------------------------------
int MotorPID_Update(int enc_l, int enc_r);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读取当前左右轮目标平均值（软启动与差速之后）
//-------------------------------------------------------------------------------------------------------------------
float MotorPID_GetTarget(void);
float MotorPID_GetTargetLeft(void);
float MotorPID_GetTargetRight(void);
float MotorPID_GetDiffPercent(void); // 当前应用的目标差速百分比：(外轮/内轮-1)*100，非实测轮速差

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读取当前输出占空比
//-------------------------------------------------------------------------------------------------------------------
int MotorPID_GetOutput(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读取当前实测速度（左右轮平均，编码器计数/10ms）
//-------------------------------------------------------------------------------------------------------------------
float MotorPID_GetMeasured(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读取使能状态
//-------------------------------------------------------------------------------------------------------------------
uint8 MotorPID_IsEnabled(void);

#endif
