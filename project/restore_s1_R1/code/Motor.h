/*********************************************************************************************************************
* 文件名称          Motor
* 功能简介          电机模块（左右两个驱动电机）
*
* 用法：
*   Motor_Init();
*   Motor_Set(左轮占空比, 右轮占空比);     正数=前进，负数=后退
*   Motor_Stop();
*
* 占空比范围：-MOTOR_DUTY_MAX ~ +MOTOR_DUTY_MAX（默认 4000，也就是 40%）
*
* 安全提醒：给电机通电前务必把车架起来，让轮子悬空！
********************************************************************************************************************/

#ifndef __MOTOR_H
#define __MOTOR_H

#include "zf_common_headfile.h"

#define MOTOR_DUTY_MAX          (4000)                  // 电机最大占空比（PWM 满量程 10000）

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     电机初始化
// 备注信息     调用前必须先执行 clock_init()
//-------------------------------------------------------------------------------------------------------------------
void Motor_Init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置左轮
// 参数说明     duty            正数前进、负数后退，超出范围会自动限幅
//-------------------------------------------------------------------------------------------------------------------
void Motor_SetLeft(int duty);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置右轮
// 参数说明     duty            正数前进、负数后退，超出范围会自动限幅
//-------------------------------------------------------------------------------------------------------------------
void Motor_SetRight(int duty);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     同时设置左右轮
// 参数说明     left, right      正数前进、负数后退
//-------------------------------------------------------------------------------------------------------------------
void Motor_Set(int left, int right);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     两个轮子都停
//-------------------------------------------------------------------------------------------------------------------
void Motor_Stop(void);

#endif
