/*********************************************************************************************************************
* 文件名称          Assistant
* 功能简介          逐飞助手 V2.0 上位机通信模块（走无线串口）
*
*   一条线同时发三样东西：
*     1. 摄像头灰度图像（188x100，无线串口 460800 下约 2~3 帧/秒）
*     2. 波形（8 个通道）
*     3. 左右边线（叠加在图像窗口上）
*   同时接收助手发下来的 8 个调试参数（滑动条）。
*
*   上位机：逐飞助手 V2.0，连接方式选"无线转串口"（选无线模块那个 COM 口）
*
* ================================ 8 个参数通道（助手 UI 通道 0~7）================================
*   通道 0 = 目标速度     (编码器计数/10ms，0~500)
*   通道 1 = 电机 P
*   通道 2 = 电机 I
*   通道 3 = 电机 D
*   通道 4 = 舵机 P
*   通道 5 = 舵机 D
*   通道 6 = 对比度阈值   (x200 尺度，0~200，默认 50)
*   通道 7 = 模式/开关    (0=停, 1=对比度巡线, 2=分段大津法巡线)
*
* ================================ 8 条波形 ================================
*   1 = ErrUse   滤波后图像偏差（调舵机 PD 主要看它）
*   2 = 舵机实际打角
*   3 = 左轮编码器（计数/10ms）
*   4 = 右轮编码器（计数/10ms）
*   5 = 电机目标速度（软启动爬坡中的值）
*   6 = 电机实测速度（两轮平均）
*   7 = 电机输出占空比
*   8 = 视野长度 Search_Stop_Line（突然变小=看不到路了）
********************************************************************************************************************/

#ifndef __ASSISTANT_H
#define __ASSISTANT_H

#include "zf_common_headfile.h"

#define ASSISTANT_OSC_CH_MAX       (8)      // 波形通道数
#define ASSISTANT_IMAGE_DIV        (4)      // 每几帧发一次图像（1=每帧，4=每4帧，更流畅的波形）

// ★ 隔离测试开关（用来判断助手示波器是不是被图像/边线大包干扰）
//   1 = 发；0 = 不发
//   先设成 0/0 只发波形，确认波形能出来；确认后再改回 1/1
#define ASSISTANT_SEND_IMAGE       (1)
#define ASSISTANT_SEND_BOUNDARY    (1)

// 参数通道号（和上面注释一一对应）
typedef enum
{
    ASST_PARAM_SPEED = 0,        // 目标速度
    ASST_PARAM_MOTOR_KP,         // 电机 P
    ASST_PARAM_MOTOR_KI,         // 电机 I
    ASST_PARAM_MOTOR_KD,         // 电机 D
    ASST_PARAM_SERVO_P,          // 舵机 P
    ASST_PARAM_SERVO_D,          // 舵机 D
    ASST_PARAM_CONTRAST,         // 对比度阈值
    ASST_PARAM_SWITCH,           // 电机开关
} assistant_param_enum;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     初始化无线串口 + 逐飞助手协议（图像/波形/边线/参数都配好）
// 返回参数     uint8    0 = 成功；1 = 无线串口自动波特率失败
//-------------------------------------------------------------------------------------------------------------------
uint8 Assistant_Init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     每圈主循环都要调：接收助手发下来的参数（更新 data[] / update_flag[]）
//-------------------------------------------------------------------------------------------------------------------
void Assistant_Poll(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     发一帧：波形 + 左右边线 + 图像（图像按 ASSISTANT_IMAGE_DIV 分频）
// 参数说明     gray        当前帧灰度图像指针（mt9v03x_image[0]）
// 参数说明     left/right  左右边线数组（每行 x 坐标）
// 参数说明     wave        波形数据（ASSISTANT_OSC_CH_MAX 个 float）
//-------------------------------------------------------------------------------------------------------------------
void Assistant_SendFrame(const uint8 *gray, const uint8 *left, const uint8 *right, const float *wave);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读参数
//-------------------------------------------------------------------------------------------------------------------
float Assistant_GetParam(assistant_param_enum ch);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读"这个参数有没有新值"（读到后自己清 0）
//-------------------------------------------------------------------------------------------------------------------
uint8 Assistant_GetUpdated(assistant_param_enum ch);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     清掉"有新值"标志
//-------------------------------------------------------------------------------------------------------------------
void Assistant_ClearUpdated(assistant_param_enum ch);

#endif
