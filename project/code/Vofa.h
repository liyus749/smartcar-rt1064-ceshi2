/*********************************************************************************************************************
* 文件名称          Vofa
* 功能简介          VOFA+ 上位机通信模块（无线串口发波形 + 收参数在线调参）
*
* 上位机              VOFA+，官网 https://www.vofa.plus/   下载中心 /downloads/
*                     主程序是【闭源免费】的 exe，下载装上就能用，不用写代码
*
* ================================ 走哪条线（已按你的硬件配好）================================
*   本模块走【无线串口模块】：逐飞库里的 UART8
*      单片机 D16(TX) / D17(RX) / D26(RTS)  ->  主板"无线模块"接口座
*      波特率 115200
*   ⚠ 这条线【传不了图像】：115200 只有 11.5KB/s，
*      一张 188x100 的图要 1.63 秒才能发完。所以：
*        波形 -> 走这条无线串口（调参用）
*        图像 -> 走并口屏（本地显示，不占串口带宽）  ← 两个不冲突，可以同时用
*
* ================================ 数据通道（8 条，前 5 调参、后 3 当眼睛）================================
*   通道1 = Err            图像偏差        <- 调 PD 主要看这条
*   通道2 = 舵机实际打角    Servo_GetAngle()
*   通道3 = 左轮转速        enc_l
*   通道4 = 右轮转速        enc_r
*   通道5 = 速度设定        run_duty
*   通道6 = Search_Stop_Line 视野长度      <- 突然变小 = 看不到路了
*   通道7 = Left_Lost_Time   左丢线行数    <- 突然变大 = 左边线找丢了
*   通道8 = Right_Lost_Time  右丢线行数
*
* ================================ VOFA+ 里怎么配 ================================
*   1. 连上：左下角选【串口】-> 选无线串口模块对应的 COM 口 -> 115200 -> 连接
*   2. 看波形：协议引擎选【JustFloat】
*   3. 调参数：
*        左栏【命令】新建一条，模式 Str(Ascii)，内容写：  P1=%f!
*        右边加【滑动条】控件，右键 -> 绑定命令 -> 选 P1=%f!
*        滑动条右键设 from / to / step（比如 0 / 10 / 0.1）
*        拖动滑动条，就往单片机发 "P1=2.5!" 这样的字符串
*
*   ★ 参数命令格式：  【字母】【数字】=【数值】!
*        P1=2.5!      -> 第 1 组 P（角度环 P）
*        P2=1.0!      -> 第 2 组 P（角速度环 P）
*        P3=0.8!      -> 第 3 组 P（速度环 P）
*        D1=-5!       -> 负数也支持
*        M=1!         -> 不带数字也可以（相当于数字 0）
*   ★ 用 '=' 和 '!' 当定界符，比用换行结尾【更抗干扰】：
*        ① 不依赖换行，丢一个字节也不会整条卡死
*        ② 一行里可以连着发多条：P1=2.5!D1=10!
*        ③ '!' 不会出现在正常数据里，不会被误触发
*
*   26 个字母 x 10 个数字 = 260 个参数槽，够用到毕业。
*
* ================================ 注意 ================================
*   1. Vofa_Init() 内部会调用 wireless_uart_init()（初始化 UART8）
*   2. 无线串口的接收缓冲区只有 64 字节，所以 Vofa_Poll() 要【每圈都调】
*   3. 115200 下，发 8 通道（36 字节）约 3ms；建议 50Hz 发送
********************************************************************************************************************/

#ifndef __VOFA_H
#define __VOFA_H

#include "zf_common_headfile.h"

// 参数槽：[字母][数字]，'A'-'Z' x '0'-'9'
//   电脑发 "P1=2.5!"  ->  Vofa_Param['P'-'A'][1] = 2.5
extern volatile float   Vofa_Param[26][10];
extern volatile uint8   Vofa_ParamFlag[26][10];     // 有新值就置 1，用完自己清 0

// 发波形的最大通道数（JustFloat 协议没有上限，这里只是给个合理值）
#define VOFA_MAX_CH            (16)

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     初始化（内部只发一行提示；真正的串口初始化在 debug_init() 里）
// 备注信息     调用前请确保 main 里已经执行过 debug_init()
//-------------------------------------------------------------------------------------------------------------------
void  Vofa_Init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     发一包波形数据（JustFloat 协议：小端 float 数组 + 帧尾 00 00 80 7F）
// 参数说明     vals        浮点数组
// 参数说明     n           通道数（1 ~ VOFA_MAX_CH）
// 使用示例     float w[4] = {Err, enc_l, enc_r, run_duty};
//              Vofa_SendWaves(w, 4);
//-------------------------------------------------------------------------------------------------------------------
void  Vofa_SendWaves(const float *vals, uint8 n);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     收电脑发来的参数命令（每圈都要调！）
// 备注信息     解析 "字母=数值" 这种格式，结果放进 Vofa_Param[] / Vofa_ParamFlag[]
//-------------------------------------------------------------------------------------------------------------------
void  Vofa_Poll(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读一个参数：Vofa_Get('P', 1) 等价于 Vofa_Param['P'-'A'][1]
// 参数说明     letter      字母（大小写都行）
// 参数说明     digit       数字 0~9
//-------------------------------------------------------------------------------------------------------------------
float Vofa_Get(char letter, uint8 digit);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     参数自检模式（死循环，不返回）—— 专门用来验证 VOFA+ 这条路通不通
// 备注信息     ★ 不需要摄像头、不需要电机、不需要 WiFi、不需要屏幕
//              它会：① 往 VOFA+ 发 4 条波形（三条正弦 + 一条"收到的参数值"）
//                    ② 同时收电脑发下来的参数
//              你在 VOFA+ 里拖滑动条，第 4 条波形的线会跟着动 —— 说明双向都通了
//-------------------------------------------------------------------------------------------------------------------
void  Vofa_SelfTest(void);

#endif
