/*********************************************************************************************************************
* 文件名称          Screen
* 功能简介          IPS200 液晶屏封装 —— 在屏幕上显示【摄像头图像 + 边线 + 中线 + 状态】
*
* 参考              逐飞官方例程 E06_04_ips200_display_demo
*                   D:\keil\智能车校赛\2寸IPS SPI接口屏幕资料\例程\RT1064\E06_04_ips200_display_demo
*
* 用到的库          libraries/zf_device/zf_device_ips200.c   （工程里已经有，不用另外添加）
*                   libraries/zf_common/zf_common_font.c     （字库，工程里也有）
*
* ================================ 怎么用 ================================
*   1. clock_init() 之后调一次   Screen_Init();
*   2. 每帧（摄像头出一帧）调一次 Screen_ShowFrame(...);
*   3. 想显示参数就调           Screen_ShowStatus(...);
*
*   ★ 和 WiFi 图传的关系：
*       SPI 屏 只占用 6 个信号脚（B0/B1/B2/B3/C18/C19），和 WiFi 模块(D12~D15/B16/B17) 不冲突，
*       两个可以同时用（屏幕看图 + WiFi 调参）。
*       并口屏 要占用 16 个脚，其中 D0~D7 就是 WiFi 模块的引脚 —— 【和 WiFi 模块不能共存】，
*       那种情况必须二选一。
*
* ================================ ★ 上电前必须确认 ★ ================================
*   IPS_SCREEN_TYPE 必须和你的实物一致！
*     怎么判断：看屏幕背面的 PCB 丝印
*        带 "SPI" 字样         -> IPS200_TYPE_SPI         （8 脚，插屏幕接口"上一排"）
*        没有 SPI 字样（并口）  -> IPS200_TYPE_PARALLEL8   （16 脚，插满整个屏幕接口）
*   类型选错 -> 屏幕不亮 或者 花屏，但不会烧（改对宏重新编译就好）
********************************************************************************************************************/

#ifndef __SCREEN_H
#define __SCREEN_H

#include "zf_common_headfile.h"

//==================================== 配置区（就改这里） ====================================

// ★ 屏幕型号：看屏幕背面丝印，SPI 屏用上面那个，并口屏用下面那个
#define IPS_SCREEN_TYPE         (IPS200_TYPE_SPI)
//#define IPS_SCREEN_TYPE       (IPS200_TYPE_PARALLEL8)

// 显示内容：0 = 灰度原图（能看反光、阈值效果，调阈值用这个）
//           1 = 二值图（黑线白底，看阈值切得干不干净）
#define SCREEN_SHOW_BINARY      (0)

// 每几帧刷一次屏幕：1 = 每帧都刷（最流畅）  2/3 = 隔帧刷（省时间，觉得卡时改成 2）
#define SCREEN_EVERY_N          (1)

// 图像显示位置和大小（1:1 显示，不缩放）
#define SCR_IMG_X               (0)
#define SCR_IMG_Y               (0)
#define SCR_IMG_W               (MT9V03X_W)          // 188
#define SCR_IMG_H               (MT9V03X_H)          // 100

// 三条线的颜色
#define SCR_COLOR_LINE_L        (RGB565_BLUE)        // 左边界
#define SCR_COLOR_LINE_M        (RGB565_GREEN)       // 中线
#define SCR_COLOR_LINE_R        (RGB565_RED)         // 右边界
#define SCR_COLOR_REF           (RGB565_GRAY)        // 画面中心参考虚线

// 状态文字从图像下方几像素开始写
#define SCR_TXT_Y               (SCR_IMG_Y + SCR_IMG_H + 4)

//==========================================================================================

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     屏幕初始化（内部会等 300ms 让主板其他外设上电完成，官方例程也是这么做的）
// 备注信息     必须在 clock_init() 之后调用；只需要调一次
//-------------------------------------------------------------------------------------------------------------------
void Screen_Init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     清屏（把整屏刷黑）
//-------------------------------------------------------------------------------------------------------------------
void Screen_Clear(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     显示一帧：摄像头图像 + 左/中/右边界 + 画面中心参考虚线
// 参数说明     gray        灰度原图      传 mt9v03x_image[0]
// 参数说明     bin         二值化图像    传 image_two_value[0]  （只有 SCREEN_SHOW_BINARY=1 时用到）
// 参数说明     line_l      左边界数组    传 line_left   （每行一个 x 坐标）
// 参数说明     line_m      中线数组      传 line_mid
// 参数说明     line_r      右边界数组    传 line_right
// 返回参数     void
// 使用示例     Screen_ShowFrame(mt9v03x_image[0], image_two_value[0], line_left, line_mid, line_right);
// 备注信息     按 SCREEN_EVERY_N 自动分频，不用自己在外面算
//-------------------------------------------------------------------------------------------------------------------
void Screen_ShowFrame(const uint8 *gray, const uint8 *bin,
                      const uint8 *line_l, const uint8 *line_m, const uint8 *line_r);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     在图像下方显示状态（每帧调，开销很小）
// 参数说明     err         图像偏差 Err
// 参数说明     state       环岛状态（不用环岛就传 0）
// 参数说明     duty        电机速度设定值
// 使用示例     Screen_ShowStatus(Err, Island_State, (int)run_duty);
//-------------------------------------------------------------------------------------------------------------------
void Screen_ShowStatus(float err, int state, int duty);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     在指定位置显示一行字符串（英文/数字）
// 备注信息     中文用 ips200_show_chinese()，字库在 zf_common_font.c 里
//-------------------------------------------------------------------------------------------------------------------
void Screen_ShowText(uint16 x, uint16 y, const char *str);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     屏幕自检（死循环，不会返回）
// 备注信息     ★ 专门用来验证"屏幕到底能不能用"，不依赖摄像头/WiFi/陀螺仪/电机
//              流程：全屏刷红绿蓝白黑 -> 显示文字数字 -> 显示一张模拟的摄像头画面+边线
//              屏幕没反应就先看屏幕背面丝印，换 IPS_SCREEN_TYPE 再试
//-------------------------------------------------------------------------------------------------------------------
void Screen_SelfTest(void);

#endif
