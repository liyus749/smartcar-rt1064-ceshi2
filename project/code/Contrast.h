/*********************************************************************************************************************
* 文件名称          Contrast
* 功能简介          对比度巡线模块（替代原来的 大津法二值化 + 最长白列 + 八邻域跟踪）
*
* 思路（按你给的参考代码）：
*   1. get_reference_point  取画面最下方一小块地面算平均灰度，再乘系数得到
*                             white_max_point / white_min_point（自适应黑白上下限）
*   2. search_reference_col 找"最长白列"所在的列，作为左右搜线的起始列（参考列）
*   3. search_line          每一行从参考列向两边搜，用对比度公式找赛道左右边界
*       对比度公式：temp3 = (temp1 - temp2) * 200 / (temp1 + temp2)
*       超过 Contrast_Ratio 就认为是"赛道 -> 背景"的边界跳变
*       好处：这个比值对光线不敏感，亮一点暗一点都差不多，抗反光
*
* 结果写回学长 Camera.c 里的全局量（island.c 环岛识别和偏差计算都读这些）：
*   Left_Line / Right_Line         每行左右边界
*   Left_Lost_Flag / Right_Lost_Flag  每行丢线标志
*   Search_Stop_Line               视野长度（最长白列长度）
*   Left_Lost_Time / Right_Lost_Time / Both_Lost_Time  丢线行数
*   Boundry_Start_Left / Boundry_Start_Right            边界起始行
*   同时生成 image_two_value[][] 二值图（屏幕显示 + 环岛里的 Longest_White_Column 用）
********************************************************************************************************************/

#ifndef __CONTRAST_H
#define __CONTRAST_H

#include "zf_common_headfile.h"

//==================================== 巡线参数（编译期固定值） ====================================

#define CONTRAST_BLACKPOINT      (50)     // 黑点下限：算出来的白点下限最低不低于 50
#define CONTRAST_WHITEMAXMUL     (13)     // 白点上限 = 参考灰度 x 13 / 10
#define CONTRAST_WHITEMINMUL     (7)      // 白点下限 = 参考灰度 x 7 / 10
#define CONTRAST_REFRENCEROW     (5)      // 取画面最下面 5 行做参考点
#define CONTRAST_SEARCHRANGE     (10)     // 搜线半径：下一行只在上一行边界 ±10 里找
#define CONTRAST_STOPROW         (0)      // 搜线停止行
#define CONTRAST_OFFSET          (3)      // 对比度比较的两个点间隔多少像素

#define CONTRAST_RATIO_DEFAULT   (50.0f)  // 对比度阈值默认值（x200 尺度，约等于 0.25 的差别和）

//==============================================================================================

// 对比度阈值：可以由逐飞助手在线调（参数通道 6）
extern volatile float Contrast_Ratio;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     巡线模块初始化（复位内部状态）
//-------------------------------------------------------------------------------------------------------------------
void Contrast_Init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     处理一帧灰度图像：算参考点 + 找参考列 + 对比度搜左右边界 + 生成二值图
// 参数说明     image      摄像头灰度图像（mt9v03x_image[0]）
// 备注信息     结果写进 Camera.c 的 Left_Line/Right_Line/丢线标志/视野长度等全局量
//-------------------------------------------------------------------------------------------------------------------
void Contrast_Process(const uint8 *image);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读取参考点灰度（给波形/屏幕看，调阈值用）
//-------------------------------------------------------------------------------------------------------------------
uint8 Contrast_GetReferencePoint(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读取参考列（最长白列所在列）
//-------------------------------------------------------------------------------------------------------------------
uint8 Contrast_GetReferenceCol(void);

#endif
